const withViews = (overrides: ViewOverrides): GalaxyView[] =>
  (Object.keys(COMMON_VIEWS) as GalaxyView["id"][]).map((id) => ({
    id,
    ...COMMON_VIEWS[id],
    ...overrides[id],
  }));

/**
 * 은하 하나를 세운다.
 *
 * 1단계의 `detail`·`observe` 를 `views` 에 따로 적지 않고 여기서 옮겨 붙이는
 * 이유는, 그것이 이 항목의 대표 설명과 같은 문장이기 때문이다. 두 벌로
 * 적으면 한쪽만 고치게 된다. 1단계의 **제목과 부제**는 은하마다 다르므로
 * `views.wide` 로 덮어쓴다.
 *
 * `easy` 만은 옮겨 붙이지 않는다. 두 글이 들어가는 칸이 다르기 때문이다.
 * 오른쪽 읽기 패널은 세로로 늘어나도 되는 자리라 쉬운 글이 120~150자이고,
 * 무대 아래 한 줄짜리 칸은 60~90자를 넘으면 장면을 가린다. 길이 예산이
 * 다르면 같은 문장일 수 없으므로, 각 은하가 `views.wide.easy` 에 무대용
 * 한 문장을 따로 적는다. 적지 않으면 `COMMON_VIEWS` 의 기본 문장이 남는다.
 */
function galaxy(base: Omit<GalaxyModel, "views">, views: ViewOverrides = {}): GalaxyModel {
  return {
    ...base,
    views: withViews({
      ...views,
      wide: { detail: base.detail, observe: base.observe, ...views.wide },
    }),
  };
}

