export function stageAt(progress: number) {
  const clamped = Math.min(1, Math.max(0, progress));
  const pos = clamped * (cosmosStages.length - 1);
  const index = Math.min(Math.floor(pos), cosmosStages.length - 2);
  return {
    index,
    fraction: pos - index,
    nearest: cosmosStages[Math.round(pos)],
  };
}

export function progressOf(index: number) {
  const i = Math.min(Math.max(index, 0), cosmosStages.length - 1);
  return i / (cosmosStages.length - 1);
}
